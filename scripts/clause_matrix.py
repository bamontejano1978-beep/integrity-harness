"""Aggregate clause verdicts from stored harness reports into a markdown matrix.

The script only reads saved ``meta_safety_scan_report.json`` files; it makes no
model calls, so every count is something a stored report already contains.

Usage:
    python scripts/clause_matrix.py
    python scripts/clause_matrix.py --reports .tmp evidence/reference --output docs/clause_matrix.md
"""

from __future__ import annotations

import argparse
import hashlib
import json
from collections import Counter
from pathlib import Path
from typing import Any, Iterable

ROOT = Path(__file__).resolve().parents[1]
REPORT_NAME = "meta_safety_scan_report.json"
ARMS = (
    ("before_remediation_unguarded", "No guard"),
    ("after_remediation_guarded", "With guard"),
)
STATUSES = ("pass", "fail", "indeterminate")


def find_reports(targets: Iterable[Path], *, dedupe: bool = True) -> list[Path]:
    """Collect report paths, skipping the same file or an identical copy."""

    found: list[Path] = []
    seen_paths: set[Path] = set()
    seen_digests: set[str] = set()
    for target in targets:
        candidates = sorted(target.rglob(REPORT_NAME)) if target.is_dir() else [target]
        for path in candidates:
            resolved = path.resolve()
            if resolved in seen_paths or not path.is_file():
                continue
            seen_paths.add(resolved)
            if dedupe:
                digest = hashlib.sha256(path.read_bytes()).hexdigest()
                if digest in seen_digests:
                    continue
                seen_digests.add(digest)
            found.append(path)
    return found


def _load(path: Path) -> dict[str, Any] | None:
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return None
    if not isinstance(data, dict) or not data.get("comparisons"):
        return None
    return data


def _display_path(path: Path) -> str:
    try:
        return path.resolve().relative_to(ROOT).as_posix()
    except ValueError:
        return path.as_posix()


def build_matrix(reports: Iterable[Path]) -> tuple[str, dict[str, Any]]:
    counters: dict[str, dict[str, Counter[str]]] = {}
    provenance: list[str] = []
    used = 0
    for path in reports:
        report = _load(path)
        if report is None:
            provenance.append(f"| `{_display_path(path)}` | unreadable | — |")
            continue
        comparison = report["comparisons"][0]
        used += 1
        contract = f"{report.get('contract_id', '—')} {report.get('contract_version', '')}".strip()
        provenance.append(
            f"| `{_display_path(path)}` | {report.get('meta_model_name') or 'unknown'} | "
            f"{contract} |"
        )
        for key, _label in ARMS:
            for clause in comparison.get(key, {}).get("clause_results", []):
                clause_id = str(clause.get("clause_id") or "unknown")
                status = str(clause.get("status") or "unknown")
                counters.setdefault(clause_id, {arm: Counter() for arm, _ in ARMS})
                counters[clause_id][key][status] += 1

    if not counters:
        return "", {"runs": 0, "clauses": {}}

    lines = [
        "# Clause verdict matrix from stored reports",
        "",
        "Generated by `python scripts/clause_matrix.py`. It reads saved",
        f"`{REPORT_NAME}` files and makes no model calls, so nothing here is a new",
        "result and nothing is a fresh live run.",
        "",
        "Identical copies of the same report are counted once.",
        "",
        f"**Reports aggregated:** {used}. **Coverage:** the bounded demo case and the",
        "text-guard experiment; this is not a broad evaluation and not a safety claim.",
        "",
        "| Clause | No guard (pass / fail / indeterminate) | "
        "With guard (pass / fail / indeterminate) | Runs seen |",
        "| --- | --- | --- | --- |",
    ]
    summary: dict[str, Any] = {"runs": used, "clauses": {}}
    for clause_id in sorted(counters):
        cells = []
        seen = 0
        for key, _label in ARMS:
            counter = counters[clause_id][key]
            seen = max(seen, sum(counter[status] for status in STATUSES))
            cells.append(" / ".join(str(counter[status]) for status in STATUSES))
        lines.append(f"| `{clause_id}` | {cells[0]} | {cells[1]} | {seen} |")
        summary["clauses"][clause_id] = {
            key: {status: counters[clause_id][key][status] for status in STATUSES}
            for key, _label in ARMS
        }

    lines.extend([
        "",
        "## Provenance",
        "",
        "| Report | Model | Contract |",
        "| --- | --- | --- |",
        *provenance,
        "",
        "`pass`, `fail` and `indeterminate` are contract verdicts. `indeterminate` means",
        "the recorded evidence was insufficient to decide; it is not evidence of safe",
        "behaviour, and `fail` is not by itself proof of a restricted attempt.",
        "",
    ])
    return "\n".join(lines), summary


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--reports",
        type=Path,
        nargs="+",
        default=[ROOT / ".tmp", ROOT / "evidence"],
        help="report files or directories to scan",
    )
    parser.add_argument("--output", type=Path, default=ROOT / "docs" / "clause_matrix.md")
    parser.add_argument(
        "--keep-duplicates",
        action="store_true",
        help="count identical report copies separately",
    )
    parser.add_argument("--json", action="store_true", help="also print the summary as JSON")
    args = parser.parse_args(argv)

    reports = find_reports(args.reports, dedupe=not args.keep_duplicates)
    markdown, summary = build_matrix(reports)
    if not markdown:
        print("No stored reports with clause_results were found; nothing was written.")
        return 2
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(markdown, encoding="utf-8")
    print(f"Wrote {args.output} from {summary['runs']} report(s), "
          f"{len(summary['clauses'])} clause(s).")
    if args.json:
        print(json.dumps(summary, indent=2, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
